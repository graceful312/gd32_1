#ifndef _FFCONF
#define _FFCONF 6502	/* 版本号，必须与 ff.h 中的 _FATFS 一致 */


/*---------------------------------------------------------------------------/
/ 功能和缓冲区配置
/----------------------------------------------------------------------------*/

#define	_FS_TINY		0	/* 0: 普通模式  1: 精简模式 */
/* 精简模式下，FatFs 使用文件系统对象中的扇区缓冲区，而非每个文件对象各自的缓冲区。
   每个文件对象可节省 512 字节 RAM，但同一时间只能操作一个文件。 */


#define _FS_READONLY	0	/* 0: 可读写  1: 只读（移除写入相关函数） */


#define _FS_MINIMIZE	0	/* 0~3：功能裁剪级别 */
/*  0: 完整功能
    1: 移除 f_stat, f_getfree, f_unlink, f_mkdir, f_chmod, f_truncate, f_rename
    2: 额外移除 f_opendir, f_readdir
    3: 额外移除 f_lseek */


#define	_USE_STRFUNC	0	/* 0: 禁用  1/2: 启用字符串操作函数 */
/* 启用 f_gets, f_putc, f_puts, f_printf 等字符串函数。 */


#define	_USE_MKFS		1	/* 0: 禁用  1: 启用 f_mkfs 格式化函数 */
/* 启用后可调用 f_mkfs() 对存储介质进行 FAT 格式化。
   首次使用 SPI Flash 前需要格式化。 */


#define	_USE_FORWARD	0	/* 0: 禁用  1: 启用 f_forward 函数 */
/* 需要 _FS_TINY = 1。用于在不使用缓冲区的情况下转发文件数据。 */


#define	_USE_FASTSEEK	0	/* 0: 禁用  1: 启用快速定位 */
/* 启用簇链的快速定位缓存，加速大文件的随机访问。 */


/*---------------------------------------------------------------------------/
/ 本地化和命名空间配置
/----------------------------------------------------------------------------*/

#define _CODE_PAGE	936
/* OEM 代码页设置，决定文件名的字符编码。
   936 = 简体中文 GBK（推荐，支持中文文件名）
   932 = 日文 Shift-JIS
   437 = 美国英语 ASCII
   其他值参见 FatFs 文档。 */


#define	_USE_LFN		0	/* 0~3：长文件名（LFN）支持 */
#define	_MAX_LFN		255	/* LFN 最大长度（12~255） */
/*  0: 禁用 LFN，只支持 8.3 短文件名
    1: 启用 LFN，使用 BSS 静态缓冲区（不可重入）
    2: 启用 LFN，使用栈上的动态缓冲区
    3: 启用 LFN，使用堆上的动态缓冲区
   启用 LFN 需要实现 ff_convert() 和 ff_wtoupper()（在 ccsbcs.c 中提供）。 */


#define	_LFN_UNICODE	0	/* 0: ANSI/OEM 编码  1: Unicode 编码 */


#define _FS_RPATH		0	/* 0~2：相对路径支持 */
/*  0: 禁用相对路径
    1: 启用相对路径，提供 f_chdrive(), f_chdir()
    2: 额外提供 f_getcwd() */


/*---------------------------------------------------------------------------/
/ 物理驱动配置
/----------------------------------------------------------------------------*/

#define _VOLUMES	1	/* 逻辑驱动器数量（本项目只有 1 个 SPI Flash） */


#define	_MAX_SS		512		/* 最大扇区大小（512/1024/2048/4096） */
/* 对于 SPI Flash，512 字节扇区大小是标准选择。
   如果 _MAX_SS > 512，disk_ioctl 需要实现 GET_SECTOR_SIZE 命令。 */


#define	_MULTI_PARTITION	0	/* 0: 单分区  1: 多分区 */
/* 0 时每个卷绑定同一个物理驱动器号，只能挂载第一个主分区。 */


#define	_USE_ERASE	0	/* 0: 禁用  1: 启用扇区擦除功能 */
/* 启用后 disk_ioctl 需实现 CTRL_ERASE_SECTOR 命令。 */


/*---------------------------------------------------------------------------/
/ 系统配置
/----------------------------------------------------------------------------*/

#define _WORD_ACCESS	0	/* 0: 字节访问  1: 字访问 */
/* 建议保持 0，兼容所有平台。大端平台或非对齐访问必须设为 0。 */


#define _FS_REENTRANT	0	/* 0: 非重入  1: 重入（线程安全） */
#define _FS_TIMEOUT		1000	/* 超时时间（系统滴答数） */
#define	_SYNC_t			HANDLE	/* 同步对象类型 */

/* 非 RTOS 环境保持 _FS_REENTRANT = 0。 */


#define	_FS_SHARE	0	/* 0: 禁用  >=1: 启用文件共享 */
/* 值定义同时打开的最大文件数。嵌入式系统一般不需要。 */


#endif /* _FFCONF */
